const bySlug = new Map(pillowCatalogue.map((p) => [p.slug, p]));

export function getPillowProductSlugs() {
  return pillowCatalogue.map((p) => p.slug);
}

export function getPillowProductDetail(slug) {
  const product = bySlug.get(String(slug || ""));
  if (!product) return null;
  const gallery = [product.image, product.hover].filter((src, i, all) => src && all.indexOf(src) === i);
  const sizes = pillowCatalogue
    .filter((p) => p.family === product.family)
    .map((p) => ({ slug: p.slug, label: p.size, price: p.price }));
  const at = pillowCatalogue.findIndex((p) => p.slug === product.slug);
  const related = [1, 2, 3, 4].map((step) => pillowCatalogue[(at + step) % pillowCatalogue.length]);
  return { ...product, gallery, sizes, related };
}

/** Fixed catalogue price. The order server asks for this at checkout. */
export function quotePillowUnit(product) {
  const total = Number(product?.price) || 0;
  return {
    ok: total > 0,
    total,
    base: total,
    name: product?.name || "",
    division: "fiber_pillow",
  };
}
